"""
Master evidence-gate refresh script -- runs every Principle 11 evaluation
script in this project's backend/evaluation/ in one command, so you don't
have to invoke each one by hand every time a detector, dataset, or model
checkpoint changes. Also the thing backend/api/main.py's
POST /evaluations/run endpoint shells out to -- triggering this from the
frontend produces the exact same result as running it here directly.

What gets run, in this fixed order (cheapest/fastest first, so a partial
run still gets you the quick wins even if a later step is slow or fails):
  1. eval_voice_spoof.py               (voice_scam / wav2vec2 spoof detector)
  2. eval_document_consistency.py      (document_fraud / PaddleOCR-VL + QR)
  3. eval_video_kyc.py                 (video_kyc_impersonation / facenet-pytorch)
  4. eval_phishing_classifier.py       (phishing_email classifier)
  5. eval_gnn.py                       (mule_network GNN)
  6. eval_fusion.py                    (fusion score -- needs the above already scored)
  7. eval_behavioral_adjustment.py     (Customer Universe behavioral corroboration on account_takeover)
  8. run_adversarial_eval.py           (xgboost/lightgbm/autoencoder adversarial rounds)

Note: eval_behavioral_adjustment.py needs data/processed/attacks_held_out.parquet
regenerated by generate/inject_attacks.py AFTER the 2026-08-31 customer_id/
country/channel wiring landed -- if it's stale (predates that change) this
step fails with a clear message telling you to regenerate, same "keep going,
don't abort the batch" treatment as any other step's failure.

Every one of these is independently idempotent (record_result upserts its
own key in metrics.json -- see evaluation/metrics.py) and safe to re-run
any number of times; none of them retrain a model, they only SCORE
whatever's already on disk under defend/models/. If one script fails (a
missing dataset, a missing dependency, whatever), this keeps going and
runs the rest anyway -- a partial refresh with several real results is
strictly more useful than aborting on the first failure and reporting
nothing, and each script's own error message already says exactly what's
missing (that's the whole point of the FileNotFoundError guidance text
written into every generate_*.py/eval_*.py pair in this project).

2026-08-31 correction: eval_document_consistency.py does NOT run in the
main `red` venv after all -- it needs paddleocr/paddlepaddle, which this
repo already keeps in its own dedicated `paddleocr_env` venv (see
requirements-paddleocr-gpu.txt) precisely because paddlepaddle's pinned
dependencies conflict with the main venv's. Confirmed by a real failure
("No module named 'paddleocr'") the first time this master script ran
document_consistency under `red`. VENV_OVERRIDES below fixes this: that
one step now launches with paddleocr_env's own python.exe instead of
whatever interpreter this script itself is running under, and falls back
to sys.executable with a printed warning if that venv doesn't exist on
this machine (never a hard crash over a missing optional venv). Every
other step still runs under sys.executable, unchanged -- eval_voice_spoof.py/
eval_video_kyc.py/etc. genuinely do run in the main `red` venv per their
own docstrings; only generate_*.py's voice_gen_env and this one eval
script's paddleocr_env are the real exceptions.

Usage:
    python evaluation/run_all_evaluations.py
    python evaluation/run_all_evaluations.py --only voice_spoof,video_kyc
    python evaluation/run_all_evaluations.py --json   # machine-readable summary, used by api/main.py
"""

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
BACKEND_DIR = EVAL_DIR.parent
METRICS_JSON = BACKEND_DIR / "defend" / "models" / "metrics.json"

STEPS = [
    ("voice_spoof", "eval_voice_spoof.py"),
    ("document_consistency", "eval_document_consistency.py"),
    ("video_kyc", "eval_video_kyc.py"),
    ("phishing_classifier", "eval_phishing_classifier.py"),
    ("gnn", "eval_gnn.py"),
    ("fusion", "eval_fusion.py"),
    ("behavioral_adjustment", "eval_behavioral_adjustment.py"),
    ("adversarial_tabular", "run_adversarial_eval.py"),
]
STEP_NAMES = [name for name, _ in STEPS]

# Step name -> venv directory name (relative to BACKEND_DIR). Only steps that
# genuinely need a different interpreter than sys.executable go here -- see
# module docstring's 2026-08-31 correction.
# document_consistency only needs paddleocr_env when it is actually going
# to use the paddlevl OCR backend. As of 2026-09-01 the detector's engine
# is selectable (see defend/pretrained/document_consistency_detector.py)
# and defaults to rapidocr, which installs into the main `red` venv with no
# paddlepaddle at all -- routing that run into paddleocr_env would launch it
# with an interpreter that has no rapidocr installed, and it would fail for
# a reason unrelated to anything real.
_DOC_OCR_BACKEND = os.environ.get("DOC_OCR_BACKEND", "").strip().lower()
VENV_OVERRIDES = ({"document_consistency": "paddleocr_env"}
                  if _DOC_OCR_BACKEND in ("", "paddlevl") else {})

# Substring match against a failed step's combined stdout+stderr -> a one-line
# fix. Cheap and worth it: the first real batch run hit both of these at once
# (Windows pagefile too small during eval_voice_spoof.py/eval_fusion.py/
# run_adversarial_eval.py, missing paddleocr module for document_consistency)
# and neither is a code bug -- surfacing the actual fix inline saves a
# round-trip every time either recurs.
_FAILURE_HINTS = [
    ("paging file", "Windows virtual memory (pagefile) is too small for this step's peak memory use "
                     "-- NOT a code bug. Fix: System Properties > Advanced > Performance Settings > "
                     "Advanced tab > Virtual Memory > Change > uncheck 'Automatically manage' > set a "
                     "custom size (Initial = your RAM size in MB, Maximum = 2-3x that) > OK > restart "
                     "your machine. Also worth closing other memory-heavy apps before re-running."),
    ("unable to allocate", "Same root cause as a 'paging file too small' error even though the wording "
                            "differs -- see that fix above."),
    ("no module named", "This step's Python environment is missing a dependency. Check VENV_OVERRIDES "
                         "at the top of this file -- if this step needs a dedicated venv that isn't "
                         "listed there yet, add it; otherwise `pip install` the missing package into "
                         "the venv you're running this from."),
]


def _hint_for(tail: str) -> "str | None":
    lower = tail.lower()
    for needle, hint in _FAILURE_HINTS:
        if needle in lower:
            return hint
    return None


def _interpreter_for(name: str) -> str:
    """sys.executable unless this step is listed in VENV_OVERRIDES AND that
    venv actually exists on this machine -- falls back to sys.executable
    with a printed warning rather than crashing over a missing optional
    venv (e.g. someone running this without ever having set up
    paddleocr_env at all)."""
    venv_name = VENV_OVERRIDES.get(name)
    if not venv_name:
        return sys.executable
    venv_dir = BACKEND_DIR / venv_name
    # Windows venvs put python.exe under Scripts/, POSIX under bin/ -- try both.
    for candidate in (venv_dir / "Scripts" / "python.exe", venv_dir / "bin" / "python"):
        if candidate.exists():
            return str(candidate)
    print(f"  WARNING: '{name}' is supposed to run in {venv_dir} but that venv doesn't exist here -- "
          f"falling back to the current interpreter, which will likely fail if the dependency really "
          f"is missing there too.", flush=True)
    return sys.executable


def _run_one(name: str, script: str, timeout: int) -> dict:
    script_path = EVAL_DIR / script
    t0 = time.monotonic()
    if not script_path.exists():
        return {"name": name, "script": script, "ok": False, "seconds": 0.0,
                "returncode": None, "tail": f"Script not found: {script_path}", "hint": None}
    interpreter = _interpreter_for(name)
    try:
        proc = subprocess.run(
            [interpreter, str(script_path)],
            cwd=str(BACKEND_DIR), capture_output=True, text=True, timeout=timeout,
        )
        dt = time.monotonic() - t0
        ok = proc.returncode == 0
        combined = (proc.stdout or "") + (proc.stderr or "")
        tail = "\n".join(combined.splitlines()[-15:])
        return {"name": name, "script": script, "ok": ok, "seconds": round(dt, 1),
                "returncode": proc.returncode, "tail": tail, "hint": None if ok else _hint_for(combined)}
    except subprocess.TimeoutExpired:
        dt = time.monotonic() - t0
        return {"name": name, "script": script, "ok": False, "seconds": round(dt, 1),
                "returncode": None, "tail": f"TIMED OUT after {timeout}s", "hint": None}
    except Exception as exc:
        return {"name": name, "script": script, "ok": False, "seconds": 0.0,
                "returncode": None, "tail": f"Failed to launch: {exc}", "hint": None}


def run_all(only: "set | None" = None, timeout: int = 1800, on_step=None) -> list:
    steps = STEPS if not only else [s for s in STEPS if s[0] in only]
    results = []
    for name, script in steps:
        print(f"\n=== {name} ({script}) ===", flush=True)
        result = _run_one(name, script, timeout)
        status = "OK" if result["ok"] else "FAILED"
        print(f"--- {name}: {status} ({result['seconds']}s) ---", flush=True)
        if not result["ok"]:
            print(result["tail"], flush=True)
            if result.get("hint"):
                print(f"  HINT: {result['hint']}", flush=True)
        results.append(result)
        if on_step:  # lets api/main.py stream progress instead of waiting for the whole batch
            on_step(result)
    return results


def scoreboard() -> dict:
    """The running 'how many attacks can we detect, defend, and adapt
    against' view this project reports after every unit of work -- reads
    whatever's currently in metrics.json, regardless of whether this
    process just ran anything."""
    if not METRICS_JSON.exists():
        return {}
    data = json.loads(METRICS_JSON.read_text())
    board = {}
    for model_name, entry in data.items():
        m = entry.get("metrics", {})
        if not isinstance(m, dict):
            continue
        board[model_name] = {
            "recall": m.get("recall"), "precision": m.get("precision"),
            "f1": m.get("f1"), "roc_auc": m.get("roc_auc"),
            "held_out_recall": entry.get("held_out_recall"),
            "n_samples": m.get("n_samples"),
        }
    return board


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", type=str, default=None,
                         help=f"Comma-separated step names to run ({', '.join(STEP_NAMES)}), default: all")
    parser.add_argument("--timeout", type=int, default=1800, help="Per-step timeout in seconds (default 1800)")
    parser.add_argument("--json", action="store_true",
                         help="Also print a machine-readable JSON summary block, used by api/main.py")
    args = parser.parse_args()

    only = set(s.strip() for s in args.only.split(",")) if args.only else None
    if only:
        unknown = only - set(STEP_NAMES)
        if unknown:
            print(f"Unknown step name(s): {', '.join(sorted(unknown))}. Valid: {', '.join(STEP_NAMES)}", file=sys.stderr)
            return 2

    results = run_all(only=only, timeout=args.timeout)
    board = scoreboard()
    summary = {
        "results": results,
        "n_ok": sum(1 for r in results if r["ok"]),
        "n_failed": sum(1 for r in results if not r["ok"]),
        "scoreboard": board,
    }

    print("\n\n==================== SUMMARY ====================")
    for r in results:
        print(f"  {'OK  ' if r['ok'] else 'FAIL'}  {r['name']:<24} {r['seconds']:>7.1f}s")
        if not r["ok"] and r.get("hint"):
            print(f"        -> {r['hint']}")
    print(f"\n{summary['n_ok']}/{len(results)} evaluation steps succeeded.")
    print("\nCurrent scoreboard (from metrics.json):")
    for model_name, m in board.items():
        print(f"  {model_name:<32} recall={m['recall']}  precision={m['precision']}  "
              f"held_out_recall={m['held_out_recall']}  n={m['n_samples']}")

    if args.json:
        print("\n===JSON_SUMMARY_START===")
        print(json.dumps(summary))
        print("===JSON_SUMMARY_END===")

    return 0 if summary["n_failed"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
